  Path _path(List<double> pts, Size size) {
    final p = Path();
    for (var i = 0; i < pts.length; i += 2) {
      final x = pts[i] / 100 * size.width;
      final y = pts[i + 1] / 100 * size.height;
      i == 0 ? p.moveTo(x, y) : p.lineTo(x, y);
    }
    return p..close();
  }

  @override
  void paint(Canvas canvas, Size size) {
    final outer = _path(_outer, size);
    canvas.drawPath(outer, Paint()..color = background);
    final stroke = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeJoin = StrokeJoin.round;
    canvas.drawPath(outer, stroke..strokeWidth = 7);
    canvas.drawPath(_path(_inner, size), stroke..strokeWidth = 2.5);
  }

  @override
  bool shouldRepaint(_FramePainter old) =>
      old.color != color || old.background != background;
}
